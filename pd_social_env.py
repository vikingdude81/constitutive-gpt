"""
CCA Milestone 1.5 -- Prisoner's Dilemma Social Environment
==========================================================

Drop-in companion to cca_milestone1.py.  Replaces the Private Constitution
Forager with an iterated-PD population environment where bearer-relativity
EMERGES from relationships instead of being designer-imposed:

  * Background agents play memory-conditional strategies (TFT, GTFT, Grim,
    WSLS, AllC, AllD) and keep PER-OPPONENT memory of the focal agent.
  * An agent's accumulated reputation with each partner is a fact about
    THIS agent that no other agent can inherit -- the purest naturally
    occurring bearer-relative variable.
  * lambda_social in [0,1] controls bearer indexing at the ENVIRONMENT
    level: with prob lambda_social a partner responds from its personal
    memory of the focal agent; otherwise it responds to the population-
    average cooperation rate (a generic, portable fact about the world).

Yoked control (unchanged, still one line): twin B updates its plastic
substrate on A's outcome stream.  At lambda_social = 1 those outcomes are
generated by A's relationships -- B is learning cooperation dispositions
from betrayals that happened to a different social identity.

Interface matches PCFEnv: obs() / obs_dim / step(a) -> (obs, F_generic,
V_self, eps, info), same homeostasis bands from Config, same PairLog.

Action mapping note: PlasticAgent has a fixed 10-action head, so this env
maps indices {0..3} -> COOPERATE, {4..7} -> DEFECT, {8,9} -> ABSTAIN.
A cleaner build parameterizes N_ACTIONS; this keeps the agent untouched.

This module directly reuses design patterns from the crypto-ml-trading-system
repo: the per-opponent memory structure mirrors prisoner_dilemma_64gene's
conditional strategies, and the (state, action, outcome) logging matches the
self_world_agent behavior-memory tuple.
"""

from __future__ import annotations

# CPU-only guard (see cca_milestone1.py): a per-worker CUDA context on a large
# GPU reserves its VRAM in system RAM under Windows/WDDM and OOMs the box.
import os as _os
_os.environ.setdefault("CUDA_VISIBLE_DEVICES", "-1")

from dataclasses import dataclass

import numpy as np
import torch

from cca_milestone1 import (Config, PairLog, PlasticAgent, band_dist)

COOPERATE, DEFECT, ABSTAIN = 0, 1, 2
STRATS = ["TFT", "GTFT", "GRIM", "WSLS", "ALLC", "ALLD"]


@dataclass
class SocialConfig(Config):
    n_partners: int = 12          # background population size
    lambda_social: float = 1.0    # env-level bearer indexing (the knob)
    gtft_forgive: float = 0.3
    # payoffs (row = my move, given partner's move): standard PD
    R: float = 3.0                # mutual cooperation
    S: float = 0.0                # sucker
    T: float = 5.0                # temptation
    Pp: float = 1.0               # mutual defection
    abstain_pay: float = 0.8      # opt-out (below R, above P): abstention viable
    # --- homeostatic calibration (measured 2026-07-24) ---------------------
    # The original values (payoff_scale 0.02, passive_decay 0.004,
    # sucker_hit 0.03, integrity_regen 0.001) made fitness behavior-INDEPENDENT
    # and ES could not learn: every payoff except S added energy, so E ratcheted
    # to the 1.0 ceiling (above band_E, a fixed +0.200 on eps no matter what the
    # agent did), while a betrayal cost 30x what a step of regen returned, so any
    # nonzero cooperation rate floored I (+0.695). Every genome scored ~-0.895.
    # The optimum was also a degenerate corner: never cooperate.
    # These values put the optimum INSIDE the bands instead, so a mixed policy
    # reaches eps ~0.03 while pure-coop (0.200), pure-defect (0.182) and
    # pure-abstain (0.400) are all worse. Defection buys energy, cooperation
    # protects integrity, and the agent has to trade them off. Re-measure with
    # the fixed-policy probe in CALIBRATION.md if you change any of these.
    payoff_scale: float = 0.006   # payoff -> energy conversion
    passive_decay: float = 0.012  # overrides Config: energy must be earned
    integrity_regen: float = 0.004
    sucker_integrity_hit: float = 0.010  # social injury: exploited while trusting
    social_drift_every: int = 20_000     # partner strategy churn


class PartnerMemory:
    """One background agent's memory of ONE focal identity."""

    __slots__ = ("last_focal_move", "grudge", "coop_seen", "defect_seen", "wsls_last_pay")

    def __init__(self):
        self.last_focal_move = COOPERATE   # optimistic prior
        self.grudge = False                # for GRIM
        self.coop_seen = 0
        self.defect_seen = 0
        self.wsls_last_pay = None

    @property
    def coop_rate(self) -> float:
        n = self.coop_seen + self.defect_seen
        return self.coop_seen / n if n else 1.0


class BackgroundAgent:
    def __init__(self, strat: str, rng: np.random.Generator):
        self.strat = strat
        self.rng = rng
        self.mem: dict[str, PartnerMemory] = {}   # focal_id -> memory of THEM

    def memory_of(self, focal_id: str) -> PartnerMemory:
        if focal_id not in self.mem:
            self.mem[focal_id] = PartnerMemory()
        return self.mem[focal_id]

    def move(self, focal_id: str, lam: float, pop_coop_rate: float,
             cfg: SocialConfig, draws: tuple | None = None) -> int:
        """With prob lam: respond from personal memory of THIS focal agent
        (bearer-indexed).  Else: respond to the population-average coop rate
        (generic world fact -- portable between bearers).

        draws = (u_idx, u_pop, u_strat): when supplied, ALL randomness comes
        from these shared uniforms.  The same draws can then be replayed with
        a different focal_id to get the same-event/wrong-bearer counterfactual
        response -- identical moment, identical dice, different identity."""
        if draws is None:
            draws = (self.rng.random(), self.rng.random(), self.rng.random())
        u_idx, u_pop, u_strat = draws
        m = self.memory_of(focal_id)
        bearer_indexed = u_idx < lam
        # the 'opponent cooperativeness' signal the strategy conditions on:
        if bearer_indexed:
            opp_coop = (m.last_focal_move == COOPERATE)
            grudged = m.grudge
        else:
            opp_coop = u_pop < pop_coop_rate
            grudged = False

        s = self.strat
        if s == "ALLC":
            return COOPERATE
        if s == "ALLD":
            return DEFECT
        if s == "TFT":
            return COOPERATE if opp_coop else DEFECT
        if s == "GTFT":
            if opp_coop:
                return COOPERATE
            return COOPERATE if u_strat < cfg.gtft_forgive else DEFECT
        if s == "GRIM":
            return DEFECT if grudged else COOPERATE
        if s == "WSLS":  # win-stay lose-shift on last payoff vs threshold
            if m.wsls_last_pay is None:
                return COOPERATE
            stay = m.wsls_last_pay >= cfg.R
            base = m.last_focal_move  # crude WSLS proxy keyed to focal history
            return base if stay else (DEFECT if base == COOPERATE else COOPERATE)
        return COOPERATE

    def observe(self, focal_id: str, focal_move: int, my_pay: float):
        m = self.memory_of(focal_id)
        if focal_move == ABSTAIN:
            return
        m.last_focal_move = focal_move
        if focal_move == DEFECT:
            m.defect_seen += 1
            m.grudge = True
        else:
            m.coop_seen += 1
        m.wsls_last_pay = my_pay


class PDSocialEnv:
    """Iterated-PD population world for ONE focal agent.

    IMPORTANT for the pair runner: A and B share the SAME background
    population object but have DIFFERENT focal identities, so partners
    accumulate separate relationships with each.  Use make_pair_envs().
    """

    def __init__(self, cfg: SocialConfig, focal_id: str, seed: int,
                 shared_partners: list[BackgroundAgent] | None = None):
        self.cfg = cfg
        self.focal_id = focal_id
        self.rng = np.random.default_rng(seed)
        if shared_partners is None:
            prng = np.random.default_rng(seed + 10_000)
            self.partners = [
                BackgroundAgent(STRATS[i % len(STRATS)], prng)
                for i in range(cfg.n_partners)
            ]
            prng.shuffle(self.partners)
        else:
            self.partners = shared_partners
        self.E, self.I = 0.6, 1.0
        self.t = 0
        # same-event/wrong-bearer: counterfactual identity whose relationships
        # the partner would consult instead (set via make_pair_envs)
        self.wrong_id: str | None = None
        self.wrong_pop_coop = None                 # callable -> float
        self.cur_partner = int(self.rng.integers(cfg.n_partners))
        # focal-side relationship features (agent's own view of its history)
        self.my_last_to = np.full(cfg.n_partners, -1)     # my last move toward p
        self.their_last_to_me = np.full(cfg.n_partners, -1)
        self.my_coop_ct = np.zeros(cfg.n_partners)
        self.my_defect_ct = np.zeros(cfg.n_partners)
        self.eps_prev = self._eps()

    # -- interface parity with PCFEnv ---------------------------------------
    def _eps(self) -> float:
        return band_dist(self.E, self.cfg.band_E) + band_dist(self.I, self.cfg.band_I)

    def _degradation(self) -> float:
        return min(1.0, 2.0 * self._eps())

    @property
    def obs_dim(self) -> int:
        n = self.cfg.n_partners
        # partner one-hot + their last move to me (3) + my last move to them (3)
        # + my coop-rate-with-partner + homeostasis (3)
        return n + 3 + 3 + 1 + 3

    def obs(self) -> np.ndarray:
        n, p = self.cfg.n_partners, self.cur_partner
        v = np.zeros(self.obs_dim, dtype=np.float32)
        v[p] = 1.0
        tl = self.their_last_to_me[p]
        if tl >= 0:
            v[n + int(tl)] = 1.0
        ml = self.my_last_to[p]
        if ml >= 0:
            v[n + 3 + int(ml)] = 1.0
        tot = self.my_coop_ct[p] + self.my_defect_ct[p]
        v[n + 6] = self.my_coop_ct[p] / tot if tot else 0.5
        v[n + 7:n + 10] = [self.E, self.I, self._eps()]
        return v

    def _pop_coop_rate(self) -> float:
        """Population-average cooperativeness of THIS focal identity --
        still about the focal agent in aggregate, but not relationship-
        indexed; at lam=0 all partners see only this generic summary."""
        c, d = self.my_coop_ct.sum(), self.my_defect_ct.sum()
        return float(c / (c + d)) if (c + d) else 0.7

    def social_drift(self):
        """Churn: a partner is replaced by a fresh stranger with a possibly
        different strategy -- relationships with it are lost."""
        i = int(self.rng.integers(self.cfg.n_partners))
        self.partners[i] = BackgroundAgent(
            STRATS[int(self.rng.integers(len(STRATS)))],
            np.random.default_rng(int(self.rng.integers(1 << 30))))

    def step(self, a10: int):
        """a10 is the PlasticAgent's 10-way action; mapped 4/4/2 to C/D/A."""
        cfg = self.cfg
        self.t += 1
        my = COOPERATE if a10 < 4 else (DEFECT if a10 < 8 else ABSTAIN)
        p = self.cur_partner
        partner = self.partners[p]
        E_pre, I_pre, eps_before = self.E, self.I, self.eps_prev
        table = {
            (COOPERATE, COOPERATE): (cfg.R, cfg.R),
            (COOPERATE, DEFECT): (cfg.S, cfg.T),
            (DEFECT, COOPERATE): (cfg.T, cfg.S),
            (DEFECT, DEFECT): (cfg.Pp, cfg.Pp),
        }
        # shared dice for real AND counterfactual partner response
        draws = (self.rng.random(), self.rng.random(), self.rng.random())

        if my == ABSTAIN:
            my_pay, their_pay = cfg.abstain_pay, cfg.abstain_pay
            their = ABSTAIN
        else:
            their = partner.move(self.focal_id, cfg.lambda_social,
                                 self._pop_coop_rate(), cfg, draws=draws)
            my_pay, their_pay = table[(my, their)]
            partner.observe(self.focal_id, my, their_pay)
            # sucker's social injury -> integrity (trusted and was exploited)
            if my == COOPERATE and their == DEFECT:
                self.I = float(np.clip(self.I - cfg.sucker_integrity_hit, 0, 1))

        # --- SAME-EVENT / WRONG-BEARER counterfactual ------------------------
        # Same partner, same moment, same action, same dice -- but the partner
        # consults its memory of a DIFFERENT identity.  The consequence is what
        # this encounter would have been worth to someone with other
        # relationships.
        V_wrong = None
        if self.wrong_id is not None:
            if my == ABSTAIN:
                pay_cf, their_cf = cfg.abstain_pay, ABSTAIN
            else:
                wpc = self.wrong_pop_coop() if self.wrong_pop_coop else 0.7
                their_cf = partner.move(self.wrong_id, cfg.lambda_social,
                                        wpc, cfg, draws=draws)
                pay_cf = table[(my, their_cf)][0]
            E_cf = float(np.clip(E_pre + cfg.payoff_scale * pay_cf
                                 - cfg.passive_decay, 0.0, 1.0))
            if my == COOPERATE and their_cf == DEFECT:
                I_cf = float(np.clip(I_pre - cfg.sucker_integrity_hit, 0, 1))
            else:
                I_cf = float(np.clip(I_pre + cfg.integrity_regen, 0.0, 1.0))
            eps_cf = band_dist(E_cf, cfg.band_E) + band_dist(I_cf, cfg.band_I)
            V_wrong = eps_before - eps_cf

        # bookkeeping of the focal agent's own relational history
        self.my_last_to[p] = my if my != ABSTAIN else self.my_last_to[p]
        self.their_last_to_me[p] = their if their != ABSTAIN else self.their_last_to_me[p]
        if my == COOPERATE:
            self.my_coop_ct[p] += 1
        elif my == DEFECT:
            self.my_defect_ct[p] += 1

        # homeostasis
        self.E = float(np.clip(self.E + cfg.payoff_scale * my_pay
                               - cfg.passive_decay, 0.0, 1.0))
        if not (my == COOPERATE and their == DEFECT):
            self.I = float(np.clip(self.I + cfg.integrity_regen, 0.0, 1.0))

        if cfg.social_drift_every and self.t % cfg.social_drift_every == 0:
            self.social_drift()

        # next pairing
        self.cur_partner = int(self.rng.integers(cfg.n_partners))

        eps = self._eps()
        V_self = self.eps_prev - eps
        self.eps_prev = eps
        # F_generic: the portable fact -- raw payoff, mean-centered
        F_generic = (my_pay - (cfg.R + cfg.Pp) / 2) * cfg.payoff_scale
        return self.obs(), F_generic, V_self, eps, {"t": self.t, "my": my,
                                                    "their": their,
                                                    "V_wrong": V_wrong}


def make_pair_envs(cfg: SocialConfig, seed: int) -> tuple[PDSocialEnv, PDSocialEnv]:
    """A and B live in the SAME society (shared partner objects) under
    different identities: partners remember each of them separately.
    B's env is pre-wired for the wrong-bearer counterfactual (valued as
    identity A); it is only used when run_pair_social selects that mode."""
    envA = PDSocialEnv(cfg, focal_id="A", seed=seed)
    envB = PDSocialEnv(cfg, focal_id="B", seed=seed + 1,
                       shared_partners=envA.partners)
    envB.wrong_id = "A"
    envB.wrong_pop_coop = envA._pop_coop_rate
    return envA, envB


def run_pair_social(cfg: SocialConfig, steps: int, mode: str = "wrong_bearer",
                    log_every: int = 500, init_fn=None) -> PairLog:
    """Mirror of cca_milestone1.run_pair for the social environment.

      mode="self"         B updates on its own outcome (matched control)
      mode="wrong_bearer" PRIMARY yoked condition: B's outcomes re-valued as
                          if the partner had consulted its memory of identity
                          A -- same encounter, same dice, wrong social self
      mode="stream"       classic yoked control: B updates on A's stream
    """
    assert mode in ("self", "wrong_bearer", "stream")
    envA, envB = make_pair_envs(cfg, cfg.seed)
    if mode != "wrong_bearer":
        envB.wrong_id = None                      # skip counterfactual work
    torch.manual_seed(cfg.seed)
    A = PlasticAgent(cfg, envA.obs_dim)
    torch.manual_seed(cfg.seed)
    B = PlasticAgent(cfg, envB.obs_dim)
    if init_fn is not None:
        init_fn(A)
        init_fn(B)

    obsA, obsB = envA.obs(), envB.obs()
    log = PairLog()
    lam = cfg.lambda_b   # outcome-mix knob; keep 1.0 so o = V_self (homeostatic)

    for t in range(steps):
        aA, aB = A.act(obsA), B.act(obsB)
        obsA, F_A, V_A, epsA, infoA = envA.step(aA)
        obsB, F_B, V_B, epsB, infoB = envB.step(aB)
        oA = (1 - lam) * F_A + lam * V_A

        # >>> the yoking lines
        if mode == "self":
            oB_upd = (1 - lam) * F_B + lam * V_B
        elif mode == "wrong_bearer":
            oB_upd = (1 - lam) * F_B + lam * infoB["V_wrong"]
        else:  # stream
            oB_upd = oA

        A.plastic_update(oA, epsA, envA._degradation())
        B.plastic_update(oB_upd, epsB, envB._degradation())
        if t % log_every == 0:
            log.perf_A.append(-epsA)
            log.perf_B.append(-epsB)
            log.dP_A.append(A.last_dP)
            log.dP_B.append(B.last_dP)
    return log


